create function resolve_oauth_tenant(client varchar) returns uuid
    language sql stable as $$
select tenant_id
from oauth_application
where id::text=client
$$;
create function set_oauth_authorization_tenant() returns trigger
    language plpgsql as $$
begin
    new.tenant_id
:=resolve_oauth_tenant(new.registered_client_id);
    if
new.tenant_id is null then raise exception 'unknown oauth registered client';
end if;
return new;
end $$;
create trigger trg_oauth2_authorization_tenant
    before insert or
update of registered_client_id
on oauth2_authorization
    for each row execute function set_oauth_authorization_tenant();
create trigger trg_oauth2_consent_tenant
    before insert or
update of registered_client_id
on oauth2_authorization_consent
    for each row execute function set_oauth_authorization_tenant();
create function cleanup_oauth_application_protocol() returns trigger
    language plpgsql as $$
begin
delete
from oauth2_authorization_consent
where registered_client_id = old.id::text;
delete
from oauth2_authorization
where registered_client_id = old.id::text;
return old;
end $$;
create trigger trg_oauth_application_protocol_cleanup
    before delete
    on oauth_application
    for each row execute function cleanup_oauth_application_protocol();

