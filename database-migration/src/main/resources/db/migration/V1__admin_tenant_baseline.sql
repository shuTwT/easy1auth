create function enforce_single_active_default_tenant_package() returns trigger
    language plpgsql as $$
begin
    if
(
select count(*)
from tenant_package
where is_default
  and status = 'active') <> 1 then
        raise exception using
            errcode = '23514',
            message = 'tenant_package must contain exactly one active default package',
            constraint = 'ck_tenant_package_single_active_default';
end if;
return null;
end;
$$;

